interface StandardNodeData {
  label?: string;
  title?: string;
  icon?: string;
  category?: string;
  description?: string;
  subtitle?: string;
  output?: string;
  onAddStep?: () => void;
}

interface Props {
  data: StandardNodeData;
  selected: boolean;
}

const StandardNode = memo(({ data, selected }: Props) => {
  const displayTitle = data.title || data.label || 'Step';
  const displayDesc = data.description || data.subtitle || data.output || '';
  const iconKey = data.icon || 'http';
  const iconEl = NodeIcons[iconKey] ?? NodeIcons.http;
  const category = data.category || 'action';

  return (
    <BaseWorkflowNode selected={selected} onAddStep={data.onAddStep}>
      <div
        className="workflow-node"
        data-category={category}
        data-selected={selected ? 'true' : undefined}
      >
        <div className="workflow-node-header">
          <span className="node-icon" data-category={category}>
            {iconEl}
          </span>
          <div className="workflow-node-text">
            <div className="node-title">{displayTitle}</div>
            {displayDesc && (
              <div className="node-description">{displayDesc}</div>
            )}
          </div>
        </div>
      </div>
    </BaseWorkflowNode>
  );
});

StandardNode.displayName = 'StandardNode';
export default StandardNode;
